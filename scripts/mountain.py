#!/usr/bin/env python3
"""Lean Lab MOUNTAIN: the one shared list of open proof work, generated from main. Written 2026-10-25 by lean-refresh with Steve live.
Usage, from the repo root:  python3 scripts/mountain.py [REF]      default REF origin/main
Scans every LeanLab/LeanLab/**/*.lean at REF for theorem or lemma declarations whose proof contains sorry.
Classes:
  CITED  a published result entered without proof on purpose: doc comment or section says cited, not proved in the lab,
         quoted, taken from the paper; or the file is a Statements.lean; or the doc names a paper id P0nnn; or the
         theorem is just `theorem x : PaperProp := by sorry`. A doc comment naming a lab unit, Unit U-nnnn, is OPEN unless it says cited itself.
  OPEN   any other sorry: a sealed statement waiting for a proof; this is the mountain
Writes MOUNTAIN.md: one row per FILE with open sorries, sorted by fewest open sorries first, which is the unit a
prover takes; claims are per file since 2026-10-26, CLAIMS/<Folder>/<FileStem>. Workers never edit statements: scripts/seal_check.py.
"""
import re, subprocess, sys, collections
REF = sys.argv[1] if len(sys.argv) > 1 else "origin/main"
def sh(c): return subprocess.run(c, shell=True, capture_output=True, text=True).stdout
files = [f for f in sh(f"git ls-tree -r --name-only {REF} -- LeanLab/LeanLab").split() if f.endswith(".lean") and "/old/" not in f]
DECL = re.compile(r"^(?:@\[[^\]]*\]\s*)?(?:(?:private|protected|noncomputable)\s+)*(theorem|lemma)\s+([^\s:({\[]+)", re.M)
rows = []; tot = collections.Counter()
# A published result entered without proof on purpose. Fixed 2026-10-25 after lean-jules found that files write
# cited, Cited., not proved in the lab, quoted in, or mark the whole Statements.lean file as paper statements.
CITED_RE = re.compile(r"\bcited\b|not proved in the lab|\bquoted\b|taken from the paper|\bpublished\b|paper\W+cited", re.I)
for f in files:
    t = sh(f"git show {REF}:'{f}'")
    t2 = re.sub(r"(?<![/-])--(?!-)[^\n]*", "", t)
    ms = list(DECL.finditer(t2))
    opens, cited = [], 0
    head = t[:1500]
    file_cited = f.endswith("/Statements.lean") or bool(re.search(r"sorry[^.]{0,40}marks a statement taken from the paper|statements? taken from the paper", head, re.I))
    for i, m in enumerate(ms):
        end = ms[i + 1].start() if i + 1 < len(ms) else len(t2)
        body = re.sub(r"/-.*?-/", "", t2[m.start():end], flags=re.S)
        if not re.search(r"\bsorry\b", body): continue
        doc = t2[max(0, m.start() - 600):m.start()]
        d = doc.rfind("/--"); docs = doc[d:] if d != -1 and "-/" in doc[d:] else ""
        sec = t2[:m.start()]; s = sec.rfind("/-!"); section = sec[s:s+300] if s != -1 else ""
        unit = re.search(r"\bUnit U-\d+", docs)
        paper_main = re.search(r"\bP\d{4}\b", docs) or re.match(r"(?:theorem|lemma)\s+\S+\s*:\s*[A-Z][\w.]*\s*:=\s*by\s+sorry", body.strip())
        if CITED_RE.search(docs) or (not unit and (CITED_RE.search(section) or file_cited or paper_main)): cited += 1
        else: opens.append(m.group(2))
    tot["cited"] += cited; tot["open"] += len(opens)
    if opens:
        folder = f.split("/")[2]
        rows.append((len(opens), folder, f, opens))
rows.sort()
out = ["# MOUNTAIN, open proof work on main", "",
       f"Generated by scripts/mountain.py from {REF}. Do not edit by hand; rerun it. OPEN sorries {tot['open']}, CITED sorries {tot['cited']}, files with open work {len(rows)}.",
       "A unit is one FILE. Claim the file with claim_unit.py, unit <Folder>/<FileStem>, when you start, prove as many OPEN sorries as you can, never edit a statement: seal_check.py must say SEAL PASS. CITED sorries are published results and are not units.", "",
       "| Open | Folder | File | Declarations |", "|---|---|---|---|"]
for n, folder, f, opens in rows:
    out.append(f"| {n} | {folder} | {f.split('LeanLab/LeanLab/')[1]} | {', '.join(opens[:8])}{' ...' if len(opens) > 8 else ''} |")
open("MOUNTAIN.md", "w").write("\n".join(out) + "\n")
print(f"OPEN {tot['open']} CITED {tot['cited']} FILES {len(rows)}")
